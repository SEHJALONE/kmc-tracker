// Vercel runs api/*.js as plain Node ESM, which can't load the extensionless
// imports used across src/. This bundles server/build-report.js (plus the src/
// code it uses) into one self-contained api/build-report.js; npm packages stay
// external and are installed by Vercel as usual. Re-run after editing anything
// build-report imports:  npm run bundle-api   — and commit the result.
import { build } from 'esbuild';
import path from 'node:path';

// Point the code's `import jsPDF from 'jspdf'` at the Node-safe shim (the shim's
// own import of 'jspdf' stays external).
const jspdfShim = {
  name: 'jspdf-node-shim',
  setup(b) {
    b.onResolve({ filter: /^jspdf$/ }, args =>
      args.importer.endsWith('jspdf-node-shim.js')
        ? { path: 'jspdf', external: true }
        : { path: path.resolve('server/jspdf-node-shim.js') });
  },
};

await build({
  entryPoints: ['server/build-report.js'],
  outfile: 'api/build-report.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  packages: 'external',
  plugins: [jspdfShim],
  define: { 'import.meta.env': '{}' },
  banner: { js: '// GENERATED by scripts/bundle-api.mjs from server/build-report.js — do not edit.' },
  logLevel: 'info',
});
